#define ESP_NULL_CHECK(ptr, tag, fmt, ...)                                                                             \
    do                                                                                                                 \
    {                                                                                                                  \
        if ((ptr) == NULL)                                                                                             \
        {                                                                                                              \
            ESP_LOGE(tag, fmt, ##__VA_ARGS__);                                                                         \
            abort();                                                                                                   \
        }                                                                                                              \
    } while (0)

#define ESP_CHECK(cond, tag, fmt, ...)                                                                                 \
    do                                                                                                                 \
    {                                                                                                                  \
        if (!(cond))                                                                                                   \
        {                                                                                                              \
            ESP_LOGE(tag, fmt, ##__VA_ARGS__);                                                                         \
            abort();                                                                                                   \
        }                                                                                                              \
    } while (0)

#ifndef ARRAY_SIZE
#define ARRAY_SIZE(arr) (sizeof(arr) / sizeof((arr)[0]))
#endif /* ARRAY_SIZE */
