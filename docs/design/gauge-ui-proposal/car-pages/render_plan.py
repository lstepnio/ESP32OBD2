#!/usr/bin/env python3
"""Render this review's restricted Markdown source without another dependency."""

from html import escape
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / "car-ui-proposal.md"


def inline(text):
    text = escape(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    return re.sub(r"\[([^\]]+)\]\((https://[^)]+)\)", r'<a href="\2">\1</a>', text)


def render():
    blocks, paragraph, items = [], [], []

    def flush():
        if paragraph:
            blocks.append("<p>" + inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()
        if items:
            blocks.append("<ul>" + "".join("<li>" + inline(i) + "</li>" for i in items) + "</ul>")
            items.clear()

    for line in SOURCE.read_text().splitlines():
        if line.startswith("#"):
            flush()
            level = len(line) - len(line.lstrip("#"))
            blocks.append(f"<h{level}>" + inline(line[level:].strip()) + f"</h{level}>")
        elif line.startswith("- "):
            if paragraph:
                flush()
            items.append(line[2:])
        elif line:
            if items:
                flush()
            paragraph.append(line)
        else:
            flush()
    flush()
    style = (
        "body{font-family:system-ui,sans-serif;background:#111315;color:#f3f4ef;"
        "max-width:900px;padding:32px 24px;margin:auto;line-height:1.7}"
        "h1{font-size:40px;line-height:1.15;letter-spacing:-1px}"
        "h2{font-size:25px;margin-top:40px;color:#f3f4ef}"
        "p,li{color:#b5bcb8}strong{color:#f3f4ef}li{margin:10px 0}"
        "a{color:#00ff70}nav{padding:12px 0}"
        "@media(max-width:600px){h1{font-size:30px}body{padding:20px}}"
    )
    (HERE / "proposal.html").write_text(
        "<!doctype html><!-- Generated by render_plan.py from docs/design/car-ui-proposal.md. -->"
        '<html lang="en"><meta charset="utf-8"><meta name="viewport" '
        'content="width=device-width,initial-scale=1"><title>Car design plan</title>'
        f"<style>{style}</style><nav><a href='index.html'>Back to screen review</a></nav>"
        "<main>" + "\n".join(blocks) + "</main></html>\n"
    )


if __name__ == "__main__":
    render()
