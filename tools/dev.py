#!/usr/bin/env python3
"""Shared local/CI checks. Hardware access and release publication are deliberately absent."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "artifacts/checks"
FIRMWARE = ROOT / "firmware/gauge"
NATIVE_TESTS = {
    "temporary_idle": [
        "tests/temporary_idle_test.c",
        "main/src/temporary_idle.c",
        "main/src/page_action.c",
    ],
    "obd_trace": ["tests/obd_trace_test.c", "main/src/obd_trace_format.c"],
    "page_action": [
        "tests/page_action_test.c",
        "main/src/page_action.c",
        "main/src/page_save_policy.c",
    ],
    "elm_response": ["tests/elm_response_test.c", "main/src/elm_response.c"],
    "core_logic": [
        "tests/core_logic_test.c",
        *[
            "main/src/" + name + ".c"
            for name in (
                "alert_engine",
                "config_trial_policy",
                "display_units",
                "json_guard",
                "pid_decoder",
                "poll_scheduler",
                "page_save_policy",
                "wifi_bulk_policy",
            )
        ],
    ],
}


def run(command, *, cwd=ROOT):
    command = [str(part) for part in command]
    print("+ " + shlex.join(command), flush=True)
    subprocess.run(command, cwd=cwd, check=True, timeout=1800)


def require(program):
    if not shutil.which(program):
        raise SystemExit(f"Missing {program}. See README.md prerequisites.")


def native(name, sources, *, includes=(), arguments=(), execute=True):
    OUTPUT.mkdir(parents=True, exist_ok=True)
    binary = OUTPUT / name
    run(
        [
            *shlex.split(os.environ.get("CC", "cc")),
            "-std=c11",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-fsanitize=address,undefined",
            "-Ifirmware/gauge/tests/stubs",
            "-Ifirmware/gauge/main/inc",
            *includes,
            *[FIRMWARE / source for source in sources],
            "-lm",
            "-o",
            binary,
        ]
    )
    if execute:
        run([binary, *arguments])


def bootstrap():
    spec = json.loads((ROOT / "tools/tooling.json").read_text())["ktlint"]
    jar = ROOT / "artifacts/tools" / f"ktlint-{spec['version']}.jar"
    if not jar.exists() or hashlib.sha256(jar.read_bytes()).hexdigest() != spec["sha256"]:
        jar.parent.mkdir(parents=True, exist_ok=True)
        temporary = jar.with_suffix(".part")
        try:
            run(
                [
                    "curl",
                    "--fail",
                    "--location",
                    "--max-time",
                    "120",
                    "--output",
                    temporary,
                    spec["url"],
                ]
            )
            if hashlib.sha256(temporary.read_bytes()).hexdigest() != spec["sha256"]:
                raise SystemExit("ktlint checksum mismatch; refusing the downloaded tool")
            temporary.replace(jar)
        finally:
            temporary.unlink(missing_ok=True)
    return jar


def format_sources(check, language):
    excluded = ("firmware/gauge/main/fonts/",)
    generated = {
        p
        for p in tracked_files((".kt", ".h", ".c", ".inc"))
        if (ROOT / p).is_file()
        and any(
            marker in (ROOT / p).read_text()[:500]
            for marker in ("Generated by ", "Generated from ")
        )
    }
    files = [
        p
        for p in tracked_files((".py", ".kt", ".kts", ".c", ".h", ".inc"))
        if not p.startswith(excluded) and p not in generated and (ROOT / p).is_file()
    ]
    binaries = Path(sys.executable).parent
    if language in ("all", "python"):
        python = [p for p in files if p.endswith(".py")]
        run([binaries / "ruff", "format", *(["--check"] if check else []), *python])
    if language in ("all", "c"):
        sources = [p for p in files if p.endswith((".c", ".h", ".inc"))]
        run(
            [binaries / "clang-format", *(["--dry-run", "--Werror"] if check else ["-i"]), *sources]
        )
    if language in ("all", "kotlin"):
        jar = bootstrap()
        run(
            [
                "java",
                "-jar",
                jar,
                *([] if check else ["--format"]),
                *[p for p in files if p.endswith((".kt", ".kts"))],
            ]
        )


def host(action):
    if action == "lint":
        run([Path(sys.executable).parent / "ruff", "check", *tracked_files((".py",))])
        run([sys.executable, "tools/validate.py"])
        run([sys.executable, "tools/platform_policy.py", "--check"])
        run([sys.executable, "tools/build_website.py", "--check"])
        for source in tracked_files((".js",)):
            run(["node", "--check", source])
        run(["git", "diff", "--check"])
        return
    if action == "test":
        run(["npm", "test", "--prefix", "web-recovery"])
        # Whole discovery prevents a new suite disappearing behind filename-specific CI globs.
        run([sys.executable, "-m", "unittest", "discover", "-s", "tools/tests", "-p", "test_*.py"])
        run(
            [
                sys.executable,
                "-m",
                "unittest",
                "discover",
                "-s",
                "docs/design/gauge-ui-proposal",
                "-p",
                "test_*.py",
            ]
        )
        run([sys.executable, "tools/obd_capture.py", "self-test"])
    for name, sources in NATIVE_TESTS.items():
        native(name, sources, execute=action == "test")


def idf_command():
    # The repository venv owns lint/tests, while IDF needs its separately installed
    # Python dependencies. Activation order must not choose the wrong interpreter.
    sdk = os.environ.get("IDF_PATH")
    environment = os.environ.get("IDF_PYTHON_ENV_PATH")
    if not sdk or not environment:
        raise SystemExit("Source ESP-IDF 5.4.1 export.sh before firmware checks.")
    python = Path(environment) / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    script = Path(sdk) / "tools/idf.py"
    if not python.is_file() or not script.is_file():
        raise SystemExit("ESP-IDF environment is incomplete; verify its export.sh setup.")
    return [python, script]


def firmware(action):
    idf = idf_command()
    if action == "build":
        run([*idf, "-C", FIRMWARE, "build"])
    elif action == "test":
        idf = os.environ.get("IDF_PATH")
        if not idf:
            raise SystemExit("Source ESP-IDF 5.4.1 export.sh before firmware checks.")
        require("cmake")
        build = OUTPUT / "ui-host"
        run(["cmake", "-S", FIRMWARE / "tests/ui_host", "-B", build])
        run(["cmake", "--build", build, "-j", "2"])
        run([build / "gauge_ui_render", OUTPUT / "ui-renders"])
        json_dir = Path(idf) / "components/json/cJSON"
        # Apple's SDK deprecates sprintf used by the pinned third-party cJSON.
        # Compile that vendor object separately so project warnings stay errors.
        OUTPUT.mkdir(parents=True, exist_ok=True)
        json_object = OUTPUT / "cJSON.o"
        run(
            [
                *shlex.split(os.environ.get("CC", "cc")),
                "-std=c11",
                "-fsanitize=address,undefined",
                "-Wno-deprecated-declarations",
                "-I" + str(json_dir),
                "-c",
                json_dir / "cJSON.c",
                "-o",
                json_object,
            ]
        )
        native(
            "config_binding",
            [
                "tests/config_binding_test.c",
                *[
                    "main/src/" + name + ".c"
                    for name in (
                        "config_document",
                        "config_runtime",
                        "diagnostic_filter",
                        "json_guard",
                        "obd_adapter_profile",
                        "pid_decoder",
                    )
                ],
                json_object,
            ],
            includes=["-I" + str(json_dir)],
            arguments=[
                "contracts/examples/config-bound-adapter.json",
                "android/app/src/main/assets/numeric_config_template.json",
            ],
        )
    elif action == "lint":
        # Compiler warnings are errors; the linked-image memory gate is part of the build.
        run([*idf, "-C", FIRMWARE, "build"])


def android(action):
    tasks = {
        "build": [":app:assembleDebug"],
        "test": [
            ":app:testDebugUnitTest",
            ":app:testReleaseUnitTest",
            ":app:compileDebugAndroidTestKotlin",
        ],
        "lint": [":app:lintDebug"],
    }
    run([ROOT / "android/gradlew", *tasks[action], "--no-daemon"], cwd=ROOT / "android")


def android_ui(action):
    if action != "test":
        raise SystemExit("android-ui supports test only; use android for build/lint.")
    classes = (
        "ConnectionStatusUiTest",
        "IdleActionsUiTest",
        "AppCleanupUiTest",
        "ReadingAlertsUiTest",
        "OptimizationUiTest",
        "AlertNotificationTest",
        "RepositoryGalleryTest",
    )
    run(
        [
            ROOT / "android/gradlew",
            ":app:ciPhoneDebugAndroidTest",
            "--no-daemon",
            "-Pandroid.testoptions.manageddevices.emulator.gpu=swiftshader_indirect",
            "-Pandroid.testInstrumentationRunnerArguments.class="
            + ",".join("com.lstepnio.egauge." + name for name in classes),
        ],
        cwd=ROOT / "android",
    )


def tracked_files(suffixes):
    paths = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).decode().split("\0")
    return [p for p in paths if p.endswith(suffixes)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("lint", "test", "build", "format", "bootstrap"))
    parser.add_argument(
        "--target", choices=("host", "firmware", "android", "android-ui", "all"), default="all"
    )
    parser.add_argument(
        "--check", action="store_true", help="Check formatting without rewriting files"
    )
    parser.add_argument("--language", choices=("all", "python", "kotlin", "c"), default="all")
    args = parser.parse_args()
    if args.action == "bootstrap":
        bootstrap()
        return
    if args.action == "format":
        format_sources(args.check, args.language)
        return
    if args.target == "android-ui":
        android_ui(args.action)
        return
    targets = {"host": host, "firmware": firmware, "android": android}
    for target, check in targets.items():
        if args.target in (target, "all"):
            check(args.action)


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as failure:
        sys.exit(failure.returncode)
    except (FileNotFoundError, subprocess.TimeoutExpired) as failure:
        sys.exit(str(failure))
