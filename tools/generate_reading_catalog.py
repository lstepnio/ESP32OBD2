"""Generate editor metadata and wire definitions from one catalog. Use --check in CI."""

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "contracts/reading-catalog.json"
KOTLIN = ROOT / "android/app/src/main/java/com/lstepnio/egauge/ReadingCatalog.kt"
TEMPLATE = ROOT / "android/app/src/main/assets/numeric_config_template.json"


def smart_interest(metadata):
    if metadata is None:
        return None
    assert isinstance(metadata, dict)
    assert set(metadata) <= {"kind", "approach", "riseRate", "riseDelta"}
    assert metadata.get("kind") in {"rpm", "runtime", "coolant", "thermal"}
    thermal = metadata["kind"] in {"coolant", "thermal"}
    assert set(metadata) == ({"kind", "approach", "riseRate", "riseDelta"} if thermal else {"kind"})
    for key, maximum in (("approach", 30), ("riseRate", 10), ("riseDelta", 30)):
        if thermal:
            value = metadata[key]
            assert type(value) in (int, float) and math.isfinite(value) and 0 < value <= maximum
    return metadata


def generated():
    rows = json.loads(CATALOG.read_text())["readings"]
    assert len({r["id"] for r in rows}) == len(rows)
    assert len({r["definition"]["id"] for r in rows}) == len(rows)
    template = json.loads(TEMPLATE.read_text())
    template["definitions"] = [r["definition"] for r in rows]

    def q(value):
        return json.dumps(value, ensure_ascii=False)

    lines = [
        "package com.lstepnio.egauge",
        "",
        "// Generated by tools/generate_reading_catalog.py. Edit contracts/reading-catalog.json.",
        "val readingCatalog: List<PidExample> = listOf(",
    ]
    for row in rows:
        d = row["definition"]
        source = "TCM" if d["request"]["service"] == "22" else "ECM"
        unit = {"degC": "°C", "kph": "km/h", "gear": ""}.get(d["unit"], d["unit"])
        fields = [
            row["id"],
            row["name"],
            source,
            d["request"]["service"] + " " + d["request"]["identifier"],
            unit,
            row["sample"],
            d["provenance"]["source"]
            if source == "TCM"
            else "Example only; vehicle support varies",
            row["category"],
            row["gaugeLabel"],
            d["id"],
        ]
        lines.append(
            "    PidExample("
            + ", ".join(map(q, fields))
            + f", {float(d['range']['min'])}, {float(d['range']['max'])}, {q(row['alertKind'])}, {row['configurationVersion']}),"
        )
    lines += [
        ")",
        "",
        'val gearPositions = linkedMapOf(13.0 to "P", 11.0 to "R", 0.0 to "N",',
        '    1.0 to "1", 2.0 to "2", 3.0 to "3", 4.0 to "4", 5.0 to "5", 6.0 to "6", 7.0 to "7", 8.0 to "8")',
        "",
        "fun readingBounds(id: String): ClosedFloatingPointRange<Double> =",
        "    readingCatalog.first { it.id == id }.let { it.minimum..it.maximum }",
        "",
        "fun alertNumber(value: Double): String = java.math.BigDecimal.valueOf(value).stripTrailingZeros().toPlainString()",
        "",
    ]
    policy = [
        "/* Generated by tools/generate_reading_catalog.py; catalog metadata, not wire fields. */"
    ]
    for row in rows:
        d = row["definition"]
        kind = row.get("samplingClass", "custom")
        assert kind in {"fast", "thermal", "slow", "custom"}
        stability = row.get("samplingStability")
        if stability is not None:
            assert kind in {"thermal", "slow"}
            assert set(stability) == {"epsilon", "windowMs"}
            assert type(stability["epsilon"]) in (int, float)
            assert math.isfinite(stability["epsilon"]) and 0 < stability["epsilon"] <= 1
            assert stability["windowMs"] == 30000
        policy.append(
            "{%s, 0x%s, 0x%s, %u, %u, READING_%s, %.9ff, %u},"
            % (
                q(d["id"]),
                d["request"]["service"],
                d["request"]["identifier"],
                d["pollIntervalMs"],
                d["staleAfterMs"],
                kind.upper(),
                stability["epsilon"] if stability else 0.0,
                stability["windowMs"] if stability else 0,
            )
        )
    interest = [
        "/* Generated by tools/generate_reading_catalog.py; presentation hints in canonical units. */"
    ]
    for row in rows:
        m = smart_interest(row.get("smartInterest"))
        if m is None:
            continue
        d = row["definition"]
        expected_unit = {"rpm": "rpm", "runtime": "s", "coolant": "degC", "thermal": "degC"}[
            m["kind"]
        ]
        assert d["unit"] == expected_unit, "Smart metadata must use canonical units"
        decoder = d["decoder"]
        fields = [
            str(decoder["byteOffset"]),
            str(decoder["byteLength"]),
            str(decoder["endian"] == "little").lower(),
            str(decoder["signed"]).lower(),
            str(decoder["numerator"]),
            str(decoder["denominator"]),
            str(float(decoder["offset"])),
            str(float(d["range"]["min"])),
            str(float(d["range"]["max"])),
        ]
        interest.append(
            "{%s, %s, 0x%s, 0x%s, 0x%s, {%s}, {%s, %s, %s, SMART_METRIC_%s}},"
            % (
                q(d["id"]),
                q(d["unit"]),
                d["request"]["service"],
                d["request"]["identifier"],
                d["request"]["responseId"],
                ", ".join(fields),
                str(float(m.get("approach", 0))),
                str(float(m.get("riseRate", 0))),
                str(float(m.get("riseDelta", 0))),
                m["kind"].upper(),
            )
        )
    return {
        ROOT / "firmware/gauge/main/src/smart_metric_catalog.inc": "\n".join(interest) + "\n",
        ROOT / "firmware/gauge/main/src/reading_policy_catalog.inc": "\n".join(policy) + "\n",
        KOTLIN: "\n".join(lines),
        TEMPLATE: json.dumps(template, separators=(",", ":"), ensure_ascii=False) + "\n",
    }


def run(check=False):
    for path, content in generated().items():
        if check:
            assert path.read_text() == content, f"Stale generated catalog: {path.relative_to(ROOT)}"
        else:
            path.write_text(content)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    run(parser.parse_args().check)
